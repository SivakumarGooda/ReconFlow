def load_ids(outdir):
    try:
        with open(os.path.join(outdir, "report-ids.json")) as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def assign_ids(ids, keys, prefix):
    """Give every key without an ID the next free <prefix>-NN. IDs already
    handed out never change, so checklist answers and links stay put."""
    used = [int(v.split("-")[1]) for v in ids.values()
            if v.startswith(prefix + "-")]
    n = max(used, default=0)
    for k in keys:
        if k not in ids:
            n += 1
            ids[k] = f"{prefix}-{n:02d}"


