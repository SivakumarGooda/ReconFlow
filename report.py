def _evidence_cmd(cmd, path):
    """Rewrite a reproduce command so its output lands in evidence/."""
    comment = ""
    m = re.search(r"\s{2,}#\s*(.*)$", cmd)
    if m:
        cmd, comment = cmd[:m.start()], m.group(1)
    cmd = cmd.strip()
    if cmd.split()[0] in INTERACTIVE:
        out = f"script -q {path} -c {shlex.quote(cmd)}"
        comment = (comment + " — " if comment else "") + "type exit to finish"
    else:
        out = f"{cmd} 2>&1 | tee {path}"
    return out + (f"   # {comment}" if comment else "")


def _entry_block(e):
    lines = [f"<!-- key: {e['key']} -->",
             f"### {e['label']} — {e['ip']}:{e['port']}/{e['proto']}", ""]
    if e["kind"] == "risky":
        lines += ["> **Risky — run only if in scope.** It acts on the target.",
                  ""]
    lines += ["```bash"] + e["cmds"] + ["```", ""]
    if e.get("expect"):
        lines += [f"Expect: {e['expect']}", ""]
    lines += ["- Result: [ ] confirmed  [ ] false positive  [ ] not tested",
              "- Severity override:", "- Notes:", ""]
    return "\n".join(lines)


def checklist_entries(found, risky, ids, infos):
    """One entry per (finding, host:port) and per risky check."""
    entries = []
    for r in risky:
        info = rf.finding_info(r["fid"], [])
        n = 0
        cmds = []
        for c in r["cmds"]:
            n += 1
            cmds.append(_evidence_cmd(
                c, f"evidence/R_{_slug(r['fid'], 30)}_{r['ip']}_{r['port']}_{n}.txt"))
        entries.append({
            "key": f"risky|{r['fid']}|{r['ip']}|{r['port']}|{r['proto']}",
            "kind": "risky", "ip": r["ip"], "port": r["port"],
            "proto": r["proto"], "sev": info["sev"],
            "label": f"{info['sev']} · {info['title']}", "cmds": cmds,
            "expect": info.get("expect", "")})
    for fid, by_key in found.items():
        info = infos[fid]
        per_host = {}
        for e in by_key.values():
            per_host.setdefault((e["ip"], e["port"], e["proto"]), e)
        for (ip, port, proto), e in sorted(per_host.items(),
                                           key=lambda kv: (_ipkey(kv[0][0]),
                                                           kv[0][1])):
            cmds, n = [], 0
            for t in info["repro"]:
                n += 1
                cmds.append(_evidence_cmd(
                    _fill(t, e), f"evidence/{ids[fid]}_{ip}_{port}_{n}.txt"))
            entries.append({
                "key": f"finding|{fid}|{ip}|{port}|{proto}", "kind": "finding",
                "ip": ip, "port": port, "proto": proto, "sev": info["sev"],
                "label": f"{ids[fid]} · {info['sev']} · {info['title']}",
                "cmds": cmds, "expect": info.get("expect", "")})
    return entries


