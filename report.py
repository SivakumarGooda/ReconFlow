def parse_checklist(outdir):
    """(answers, new_findings, conflicts). answers: key -> {result,
    severity, notes, evidence: [(cmd line, path)]}."""
    path = os.path.join(outdir, "manual-checklist.md")
    if not os.path.exists(path):
        return {}, [], []
    with open(path) as f:
        text = f.read()
    answers, conflicts = {}, []
    parts = re.split(r"<!-- key: (.+?) -->", text)
    for key, body in zip(parts[1::2], parts[2::2]):
        body = re.split(r"(?m)^## ", body)[0]
        result = None
        m = re.search(r"Result:(.*)", body)
        if m:
            ticked = re.findall(r"\[[xX]\]\s*(confirmed|false positive|not tested)",
                                m.group(1))
            if len(set(ticked)) == 1:
                result = ticked[0]
            elif ticked:
                conflicts.append(key)
        sev = re.search(r"Severity override:[ \t]*(\w*)", body)
        sev = sev.group(1).capitalize() if sev else ""
        notes = re.search(r"Notes:[ \t]*(.*(?:\n[ \t]{2,}\S.*)*)", body)
        answers[key.strip()] = {
            "result": result,
            "severity": sev if sev in rf.SEV_ORDER else "",
            "notes": " ".join(notes.group(1).split()) if notes else "",
            "evidence": re.findall(
                r"(?m)^(.*?(?:\btee|\bscript -q)\s+(evidence/\S+).*)$", body)}
    new = []
    plain = re.sub(r"(?s)<!--.*?-->", "", text)
    for m in re.finditer(r"(?ms)^### NEW:[ \t]*(.+?)$(.*?)(?=^#{2,3} |\Z)",
                         plain):
        body = m.group(2)
        field = lambda k: (re.search(rf"(?m)^- {k}:[ \t]*(.*)$", body) or
                           [None, ""])[1].strip()
        affected = []
        for a in re.split(r"[,\s]+", field("Affected")):
            am = re.match(r"([\w.:-]+?):(\d+)(?:/(tcp|udp))?$", a)
            if am:
                affected.append((am.group(1), int(am.group(2)),
                                 am.group(3) or "tcp"))
            elif a:
                affected.append((a, 0, "tcp"))
        sev = field("Severity").capitalize()
        new.append({"title": m.group(1).strip(),
                    "sev": sev if sev in rf.SEV_ORDER else "Medium",
                    "affected": affected, "why": field("Description"),
                    "evidence": field("Evidence"), "fix": field("Fix")})
    return answers, new, conflicts


# evidence/<name>_<ip>_<port>_<n>.txt — what tools/rf-helpers.sh `each`
# writes (and the checklist's own naming). Read even when no checklist entry
# points to it, so a check looped over every target reaches the report.
EVIDENCE_NAME = re.compile(
    r"^(?P<name>.+)_(?P<ip>\d{1,3}(?:\.\d{1,3}){3})_(?P<port>\d+)_\d+\.txt$")


def evidence_jobs(outdir, answers, records):
    """Evidence files -> pseudo check jobs (source Manual), so the same
    detection rules judge hand-run output: files a checklist entry points
    to, plus any evidence/<name>_<ip>_<port>_<n>.txt for a scanned
    host:port. Also returns the checklist keys that have evidence."""
    by_hp = {(r["ip"], r["port"], r["proto"]): r for r in records}
    jobs, attached = [], defaultdict(list)
    for key, a in answers.items():
        try:
            _, fid, ip, port, proto = key.split("|")
            port = int(port)
        except ValueError:
            continue
        for cmd, rel in a["evidence"]:
            p = os.path.join(outdir, rel)
            if not os.path.isfile(p) or not os.path.getsize(p):
                continue
            with open(p, errors="replace") as f:
                text = _clean(f.read())
            attached[key].append(rel)
            r = by_hp.get((ip, port, proto))
            for prof in (rf.profiles_for(r) if r else ["unknown"]):
                jobs.append({"group": "", "ip": ip, "port": port,
                             "proto": proto, "prof": prof, "cmd": cmd,
                             "status": "ok", "out": text, "source": "Manual",
                             "evidence": rel})
    linked = {rel for v in attached.values() for rel in v}
    evdir = os.path.join(outdir, "evidence")
    for fn in sorted(os.listdir(evdir)) if os.path.isdir(evdir) else ():
        m = EVIDENCE_NAME.match(fn)
        rel = f"evidence/{fn}"
        if not m or rel in linked:
            continue
        ip, port = m.group("ip"), int(m.group("port"))
        recs = [r for (i, p, _), r in by_hp.items() if (i, p) == (ip, port)]
        p = os.path.join(evdir, fn)
        if not recs or not os.path.getsize(p):
            continue  # not a scanned host:port — never guess
        with open(p, errors="replace") as f:
            text = _clean(f.read())
        first = text.split("\n", 1)[0]
        cmd = first[2:] if first.startswith("$ ") else rel
        for r in recs:
            for prof in rf.profiles_for(r):
                jobs.append({"group": "", "ip": ip, "port": port,
                             "proto": r["proto"], "prof": prof, "cmd": cmd,
                             "status": "ok", "out": text, "source": "Manual",
                             "evidence": rel})
    return jobs, attached


def find_strays(outdir, answers):
    """Checklist evidence and msf-manual*.log that landed outside the output
    folder — a command run from the wrong directory, or a bare `spool`.
    Looks in the current, parent and home folders; only reports, never moves.
    Returns [(found path, where it belongs)]."""
    out_abs = os.path.abspath(outdir)
    dirs = []
    for d in (os.getcwd(), os.path.dirname(out_abs), os.path.expanduser("~")):
        d = os.path.abspath(d)
        if d != out_abs and d not in dirs:
            dirs.append(d)
    strays = []
    for a in answers.values():
        for _, rel in a["evidence"]:
            if os.path.isfile(os.path.join(outdir, rel)):
                continue
            for d in dirs:
                p = os.path.join(d, rel)
                if os.path.isfile(p) and (p, rel) not in strays:
                    strays.append((p, rel))
    for d in dirs:
        for p in sorted(glob.glob(os.path.join(d, "msf-manual*.log"))):
            want = os.path.basename(p)
            if os.path.exists(os.path.join(outdir, want)):
                want = f"{want[:-4]}-moved.log"  # keep both sessions
            strays.append((p, want))
    return strays


