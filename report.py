#!/usr/bin/env python3
"""
ReconFlow report builder (report.py).

    python3 report.py <output folder>

Never contacts a target. It reads what the runs left in the output folder
and rebuilds, from scratch, everything generated from it — run it as often
as you like:

  reads   results.json          recon results (written by reconflow.py)
          msf-run.log           the Metasploit run started by reconflow.py
          msf-manual*.log       your own msfconsole sessions (`spool`)
          manual-checklist.md   your answers: confirmed / false positive / …
          evidence/             output of the safe checks, the checklist
                                commands and tools/rf-helpers.sh
                                (<name>_<ip>_<port>_<n>.txt)
  writes  FINDINGS.md           the report (incl. "Safe checks — possible
                                issues": results a person must judge)
          vulnerabilities/      one file per finding: by severity, by host;
                                hosts/<finding>.txt = its ip:port list
          report-ids.json       keeps finding IDs stable between rebuilds
          manual-checklist.md   only ADDS entries for new findings — your
                                answers are never changed
          msf-manual.rc         only if missing (folders from older versions)

It also warns about checklist evidence or msf-manual*.log it finds in your
current, parent or home folder — work run from the wrong place. It never
moves them; it prints the `mv` to run.

reconflow.py calls build() at the end of every run, so the first report and
every rebuild come from the same code.
"""

