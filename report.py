def host_status(fid, e, srcs, answers, attached):
    """Status + notes for one affected host:port of a finding. srcs: every
    source that saw this finding on this host:port."""
    hp = f"{e['ip']}|{e['port']}|{e['proto']}"
    keys = [f"finding|{fid}|{hp}", f"risky|{fid}|{hp}"]
    ans = next((answers[k] for k in keys if k in answers), {})
    res = ans.get("result")
    if res == "false positive":
        st = "False positive"
    elif res == "confirmed" or srcs & MANUAL_SOURCES:
        st = "Confirmed"
    elif res == "not tested":
        st = "Not tested"
    elif any(attached.get(k) for k in keys):
        st = "Not reproduced"
    else:
        st = "Detected"
    # Seen by automation in an earlier run (it has a checklist entry) but
    # not in this one — kept because you confirmed it.
    stale = (f"finding|{fid}|{hp}" in answers
             and not srcs & {"Recon", "Metasploit (auto)"})
    return st, ans.get("notes", ""), ans.get("severity", ""), stale


def summarize(statuses):
    live = [s for s in statuses if s != "False positive"]
    if not live:
        return "False positive"
    counts = {s: live.count(s) for s in STATUS_ORDER if s in live}
    if len(counts) == 1:
        return next(iter(counts))
    return ", ".join(f"{n} {s.lower()}" for s, n in counts.items())


