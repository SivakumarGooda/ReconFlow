MSF_LINE = (re.compile(r"^\[([+*])\]\s+(\d{1,3}(?:\.\d{1,3}){3}):(\d+)\s*-?\s*(.*)$"),
            re.compile(r"^\[([+*])\]\s+\[(\d{1,3}(?:\.\d{1,3}){3}):(\d+)\]\s*(.*)$"))
# UDP modules print no port (snmp_enum: `[+] 10.0.0.5, Connected.`); the
# port then comes from the last `RPORT => N` echoed by msfconsole.
MSF_LINE_NOPORT = re.compile(
    r"^\[([+*])\]\s+(\d{1,3}(?:\.\d{1,3}){3})(?:,|\s+-)\s*(.*)$")


def parse_msf_log(path, source, outdir):
    """[{source, file, module, level, ip, port, msg, line}] — deduplicated,
    with the module taken from the preceding `use …` or console prompt."""
    hits, seen, module, rport = [], set(), "", None
    rel = os.path.relpath(path, outdir)

    def add(level, ip, port, msg, line):
        key = (module, line)
        if key not in seen:
            seen.add(key)
            hits.append({"source": source, "file": rel, "module": module,
                         "level": level, "ip": ip, "port": port,
                         "msg": msg.strip(), "line": line})

    with open(path, errors="replace") as f:
        for raw in f:
            line = _clean(raw).rstrip()
            m = re.search(r"\buse\s+((?:auxiliary|exploit|post)/\S+)", line)
            if m:
                module, rport = m.group(1), None
                continue
            m = re.search(r"\b(auxiliary|exploit|post)\(([^)]+)\)\s*>", line)
            if m:
                new = f"{m.group(1)}/{m.group(2)}"
                if new != module:
                    module, rport = new, None
            m = re.match(r"^RPORT\s*=>\s*(\d+)\s*$", line)
            if m:
                rport = int(m.group(1))
                continue
            for rx in MSF_LINE:
                m = rx.match(line)
                if m:
                    add(m.group(1), m.group(2), int(m.group(3)), m.group(4),
                        line)
                    break
            else:
                m = MSF_LINE_NOPORT.match(line)
                if m and rport:
                    add(m.group(1), m.group(2), rport, m.group(3), line)
    return hits


def msf_sources(outdir):
    """(path, source) for every Metasploit log in the folder."""
    out = []
    auto = os.path.join(outdir, "msf-run.log")
    if os.path.exists(auto):
        out.append((auto, "Metasploit (auto)"))
    for p in sorted(glob.glob(os.path.join(outdir, "msf-manual*.log"))):
        out.append((p, "Metasploit (manual)"))
    return out


def apply_msf(found, hits, protos):
    """Map Metasploit result lines onto findings (rf.MSF_RULES). Returns the
    `[+]` lines no rule claimed — shown as 'Other Metasploit output'."""
    other = []
    for h in hits:
        proto = protos.get((h["ip"], h["port"]), "tcp")
        matched = False
        for mod_rx, msg_rx, fid in rf.MSF_RULES:
            # `[*]` lines are status chatter, except smb_version's signing.
            if h["level"] == "*" and fid != "smb-signing":
                continue
            if re.search(mod_rx, h["module"]) and re.search(msg_rx, h["msg"]):
                fmt = {}
                if fid.startswith("nse:"):
                    script = fid[4:]
                    fmt = {"title": rf.MSF_NSE_TITLES.get(script, script),
                           "cmd": f"nmap -Pn -p{h['port']} --script {script} "
                                  f"{h['ip']}"}
                rf.add_finding(found, fid, h["ip"], h["port"], proto,
                               h["source"], h["file"],
                               f"{h['module']}\n{h['line']}", "", fmt)
                matched = True
        if not matched and h["level"] == "+":
            other.append(h)
    return other


