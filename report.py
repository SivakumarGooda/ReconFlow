def _aff_line(a):
    hp = f"{a['ip']}:{a['port']}/{a['proto']}"
    d = f" — {a['detail']}" if a["detail"] else ""
    extra = " · *not seen in latest scan*" if a["stale"] else ""
    return (f"`{hp}`{d} — **{a['status']}** "
            f"({', '.join(a['sources'])}){extra}")


def host_list_name(f):
    """vulnerabilities/hosts/<name>: the finding id from the catalogue
    (vsftpd-234.txt, nse-smb-vuln-ms17-010.txt) — the same every run, so
    the docs can name it; your own findings use their M-NN id."""
    return (f["fid"] or f["id"].lower()).replace(":", "-") + ".txt"


def _ev_link(path, depth):
    if path.endswith(".md") or not path:
        return f"`{path}`"
    return f"[`{path}`]({'../' * depth}{path})"


def write_vulnerabilities(ctx):
    """vulnerabilities/: INDEX.md, <severity>/, false-positives/, by-host/."""
    vdir = os.path.join(ctx["outdir"], "vulnerabilities")
    shutil.rmtree(vdir, ignore_errors=True)
    os.makedirs(os.path.join(vdir, "by-host"))
    findings = ctx["findings"]
    for f in findings:
        info, path = f["info"], os.path.join(vdir, f["file"])
        os.makedirs(os.path.dirname(path), exist_ok=True)
        L = [GENERATED, f"# {f['id']} · {info['title']}", "",
             "| | |", "|---|---|", f"| Severity | {info['sev']} |",
             f"| Status | {f['status']} |",
             f"| Detected by | {', '.join(f['sources'])} |", "",
             f"**Why it matters:** {info['why']}", "", "## Affected", "",
             "| Host | Status | Detected by | Detail |", "|---|---|---|---|"]
        for a in f["aff"]:
            st = a["status"] + (" (not seen in latest scan)" if a["stale"] else "")
            L.append(f"| `{a['ip']}:{a['port']}/{a['proto']}` | {st} | "
                     f"{', '.join(a['sources'])} | {a['detail'] or ''} |")
        L += ["", "## Evidence", ""]
        for a in f["aff"]:
            L += [f"### {a['ip']}:{a['port']}/{a['proto']}", ""]
            for ev in a["evidence"]:
                L += [f"**{ev['source']}** — {_ev_link(ev['file'], 2)}", "",
                      _fence(ev["excerpt"]), ""]
            if a["notes"]:
                L += [f"**Your notes:** {a['notes']}", ""]
        if info.get("repro"):
            L += ["## Reproduce", "", "```bash"]
            seen = set()
            for a in f["aff"]:
                block = tuple(_fill(t, a) for t in info["repro"])
                if block not in seen:
                    seen.add(block)
                    L += [f"# {a['ip']}:{a['port']}"] + list(block)
            L += ["```", ""]
        if info.get("expect"):
            L += [f"**Expected:** {info['expect']}", ""]
        if info.get("next"):
            L += [f"**Next steps:** {info['next']}", ""]
        if info.get("msf"):
            L += [f"**Metasploit reference:** `{info['msf']}` — not run by "
                  "ReconFlow; see docs/workflow/MANUAL_METASPLOIT.md.", ""]
        L += [f"**Fix:** {info['fix']}", ""]
        with open(path, "w") as fh:
            fh.write("\n".join(L))

    # hosts/<finding>.txt — the affected ip:port list of each finding, for
    # running a manual check / exploit confirmation against exactly those
    # hosts (tools/rf-helpers.sh: each NAME vulnerabilities/hosts/X.txt ...).
    os.makedirs(os.path.join(vdir, "hosts"))
    for f in findings:
        if f["status"] == "False positive":
            continue
        lines = sorted({(a["ip"], a["port"]) for a in f["aff"]
                        if a["port"] and a["status"] != "False positive"},
                       key=lambda hp: (_ipkey(hp[0]), hp[1]))
        if lines:
            with open(os.path.join(vdir, "hosts", host_list_name(f)),
                      "w") as fh:
                fh.write("".join(f"{ip}:{port}\n" for ip, port in lines))

    # by-host/
    per_host = defaultdict(list)
    for f in findings:
        for a in f["aff"]:
            per_host[a["ip"]].append((f, a))
    other = defaultdict(list)
    for h in ctx["other_msf"]:
        other[h["ip"]].append(h)
    for ip in sorted(set(per_host) | set(other), key=_ipkey):
        hn = ctx["hosts"].get(ip, {})
        L = [GENERATED, f"# {ip}" + (f" ({hn['hostname']})" if hn.get("hostname") else ""), ""]
        if hn.get("os"):
            L += [f"OS: {hn['os']}", ""]
        L += ["| ID | Severity | Finding | Port | Status |",
              "|---|---|---|---|---|"]
        for f, a in sorted(per_host[ip], key=lambda fa: (
                rf.SEV_ORDER[fa[0]["info"]["sev"]], fa[1]["port"])):
            L.append(f"| [{f['id']}](../{f['file']}) | {f['info']['sev']} | "
                     f"{f['info']['title']} | {a['port']}/{a['proto']} | "
                     f"{a['status']} |")
        if other[ip]:
            L += ["", "## Other Metasploit output", "", "```text"]
            L += [f"{h['line']}   ({h['module'] or '?'}, {h['source']})"
                  for h in other[ip]] + ["```"]
        with open(os.path.join(vdir, "by-host", f"{ip.replace(':', '_')}.md"),
                  "w") as fh:
            fh.write("\n".join(L) + "\n")

    # INDEX.md
    L = [GENERATED, f"# Vulnerabilities — {os.path.basename(os.path.abspath(ctx['outdir']))}",
         "", "One file per finding, grouped by severity; `by-host/` lists "
         "them per host; `hosts/<finding>.txt` is each finding's ip:port "
         "list (for `tools/rf-helpers.sh`). Rebuilt by `report.py` — record "
         "results in `../manual-checklist.md`.", "",
         "| ID | Severity | Finding | Affected | Detected by | Status |",
         "|---|---|---|---|---|---|"]
    for f in findings:
        where = ", ".join(sorted({f"{a['ip']}:{a['port']}" for a in f["aff"]}))
        L.append(f"| [{f['id']}]({f['file']}) | {f['info']['sev']} | "
                 f"{f['info']['title']} | {where} | {', '.join(f['sources'])} "
                 f"| {f['status']} |")
    L += ["", "**By host:** " + " · ".join(
        f"[{ip}](by-host/{ip.replace(':', '_')}.md)"
        for ip in sorted(set(per_host) | set(other), key=_ipkey))]
    with open(os.path.join(vdir, "INDEX.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


def write_findings(ctx):
    """FINDINGS.md — summary, scan results per IP, every finding with its
    status and reproduce steps, Metasploit output, manual follow-up."""
    res, outdir, findings = ctx["res"], ctx["outdir"], ctx["findings"]
    live = [f for f in findings if f["status"] != "False positive"]
    fps = [f for f in findings if f["status"] == "False positive"]
    sev_count = defaultdict(int)
    for f in live:
        sev_count[f["info"]["sev"]] += 1
    records, hosts = ctx["records"], ctx["hosts"]
    by_host = defaultdict(list)
    for r in records:
        by_host[r["ip"]].append(r)
    all_ips = sorted(set(hosts) | set(by_host), key=_ipkey)
    now = f"{_dt.datetime.now():%Y-%m-%d %H:%M}"

    answered = sum(1 for a in ctx["answers"].values() if a["result"])
    total = len(ctx["answers"])
    n_evidence = sum(len(v) for v in ctx["attached"].values())
    msf_auto = [h for h in ctx["hits"] if h["source"] == "Metasploit (auto)"]
    msf_man = [h for h in ctx["hits"] if h["source"] == "Metasploit (manual)"]
    auto_log = any(s == "Metasploit (auto)" for _, s in ctx["msf_logs"])
    man_logs = [os.path.relpath(p, outdir) for p, s in ctx["msf_logs"]
                if s == "Metasploit (manual)"]

    L = [GENERATED, f"# Findings — {os.path.basename(os.path.abspath(outdir))}", "",
         f"Report built {now} by `report.py` from recon run {res['generated']}. "
         "**Authorized targets only.** Rebuild any time with "
         f"`python3 report.py {shlex.quote(outdir)}` — it never touches a "
         "target.", "",
         "| | |", "|---|---|",
         "| In scope | " + (f"`{res['targets_file']}`" if res.get("targets_file")
                            else "n/a (--from-xml)") + " |",
         "| Out of scope | " + (f"`{res['exclude_file']}`" if res.get("exclude_file")
                                else "none") + " |",
         f"| Hosts up | {len(all_ips)} |", f"| Open ports | {len(records)} |",
         "| Findings | " + (", ".join(f"{sev_count[s]} {s}" for s in rf.SEV_ORDER
                                     if sev_count[s]) or "none")
         + (f" (+{len(fps)} false positive)" if fps else "") + " |",
         "| Metasploit (auto) | " + (f"{len(msf_auto)} result line(s) — "
                                     "`msf-run.log`" if auto_log
                                     else "not run") + " |",
         "| Metasploit (manual) | " + (f"{len(msf_man)} result line(s) — "
                                       + ", ".join(f"`{p}`" for p in man_logs)
                                       if man_logs
                                       else "no `msf-manual*.log` yet") + " |",
         f"| Manual checklist | {answered} of {total} entries answered, "
         f"{n_evidence} evidence file(s) — `manual-checklist.md` |", ""]
    for c in res.get("scan_cmds", []):
        L.append(f"Scan: `{c}`  ")

    L += ["", "## Summary", ""]
    if live:
        L += ["| ID | Severity | Finding | Affected | Detected by | Status |",
              "|---|---|---|---|---|---|"]
        for f in live:
            where = ", ".join(sorted({f"{a['ip']}:{a['port']}" for a in f["aff"]}))
            L.append(f"| [{f['id']}](#{f['id'].lower()}) | {f['info']['sev']} | "
                     f"{f['info']['title']} | {where} | "
                     f"{', '.join(f['sources'])} | {f['status']} |")
    else:
        L.append("_No findings._")
    L += ["", "Every finding also has its own file with the evidence lines in "
          "[`vulnerabilities/`](vulnerabilities/INDEX.md)."]

    L += ["", "## Scan results (nmap)", "",
          "Full output: `scan-tcp.nmap` and `scan-udp.nmap`. Per-port checks: "
          "`service-checks/`.", ""]
    fl = defaultdict(set)
    for f in live:
        for a in f["aff"]:
            fl[(a["ip"], a["port"], a["proto"])].add(f["id"])
    for ip in all_ips:
        h = hosts.get(ip, {})
        L.append(f"### {ip}" + (f" ({h['hostname']})" if h.get("hostname") else ""))
        if h.get("os"):
            L.append(f"OS: {h['os']}  ")
        recs = sorted(by_host.get(ip, []), key=lambda x: (x["proto"], x["port"]))
        if not recs:
            L += ["_Host is up but no open ports were found — see the manual "
                  "follow-up section._", ""]
            continue
        L += ["| Port | Service | Version | Findings |", "|---|---|---|---|"]
        for r in recs:
            ver = " ".join(x for x in (r["product"], r["version"],
                                       r["extrainfo"]) if x)
            tun = "ssl/" if r["tunnel"] == "ssl" else ""
            L.append(f"| {r['port']}/{r['proto']} | {tun}{r['name'] or '?'} | "
                     f"{ver.replace('|', '/')} | "
                     f"{', '.join(sorted(fl.get((r['ip'], r['port'], r['proto']), [])))} |")
        L.append("")

    def finding_section(f):
        info = f["info"]
        out = [f'<a id="{f["id"].lower()}"></a>',
               f"### {f['id']} · {info['sev']} · {info['title']}", "",
               f"**Status:** {f['status']} · **Detected by:** "
               f"{', '.join(f['sources'])} · **Details & evidence:** "
               f"[`vulnerabilities/{f['file']}`](vulnerabilities/{f['file']})", "",
               f"**Why it matters:** {info['why']}", "",
               f"**Affected ({len(f['aff'])}):**"]
        out += [f"- {_aff_line(a)}" for a in f["aff"]]
        if info.get("repro"):
            out += ["", "**Reproduce:**", "```bash"]
            seen = set()
            for a in f["aff"]:
                block = tuple(_fill(t, a) for t in info["repro"])
                if block not in seen:
                    seen.add(block)
                    out += [f"# {a['ip']}:{a['port']}"] + list(block)
            out += ["```"]
        if info.get("expect"):
            out += ["", f"**Expected:** {info['expect']}"]
        if info.get("next"):
            out += ["", f"**Next steps:** {info['next']}"]
        if info.get("msf"):
            out += ["", f"**Metasploit reference:** `{info['msf']}` — not run "
                    "by ReconFlow; see `docs/workflow/MANUAL_METASPLOIT.md`."]
        out += ["", f"**Fix:** {info['fix']}", ""]
        return out

    L += ["## Findings", ""]
    for f in live:
        L += finding_section(f)

    if ctx["other_msf"]:
        L += ["## Other Metasploit output", "",
              "`[+]` lines no finding rule claimed — review them:", "", "```text"]
        L += [f"{h['line']}   ({h['module'] or '?'}, {h['source']})"
              for h in ctx["other_msf"][:150]]
        L += ["```", ""]

    # ---- safe checks (safechecks.py): results only a person can judge
    import safechecks
    possible = safechecks.review_items(outdir, records)
    if possible:
        L += ["## Safe checks — possible issues (check, then report)", "",
              "The safe checks saved output that **may** show a problem no "
              "rule can judge. For each one: run the command below (from "
              "the output folder) or open the evidence file, and compare "
              "with *Look for*. Real issue → add a block under *3. New "
              "findings* in `manual-checklist.md` with `Evidence:` pointing "
              "to the file, then rebuild. Not an issue → ignore it. All "
              "files, including the ones with nothing in them: "
              "`SAFE-CHECKS.md`.", "",
              "| # | Check | Host |", "|---|---|---|"]
        for n, it in enumerate(possible, 1):
            L.append(f"| [{n}](#possible-{n}) | `{it['check']}` — "
                     f"{it['what']} | {it['target']} |")
        L.append("")
        for n, it in enumerate(possible, 1):
            L += [f'<a id="possible-{n}"></a>',
                  f"**{n}. `{it['check']}` — {it['target']}**", "",
                  f"- **Look for:** {it['look']}",
                  f"- **Evidence:** [`{it['file']}`]({it['file']})", "",
                  "```bash", it["repro"], "```", ""]

    # ---- what still needs a human
    items = [tuple(i) for i in res["manual"]["auto"]]
    if possible:
        items.insert(0, (f"{len(possible)} possible issue(s) from the safe "
                         "checks — review and report",
                         ["See *Safe checks — possible issues* above; "
                          "each row names the evidence file and what to "
                          "look for."]))
    # Runs from before this item existed get it on rebuild.
    login = rf.login_item(ctx["records"])
    if login and not any(t.startswith(rf.LOGIN_TITLE) for t, _ in items):
        at = next((i + 1 for i, (t, _) in enumerate(items)
                   if "risky check" in t), 0)
        items.insert(at, login)
    items += [
        ("No automated check: " + t, d) for t, d in res["manual"]["none"]]
    pending = [k for k, a in ctx["answers"].items() if not a["result"]
               and not ctx["attached"].get(k)]
    if pending:
        items.insert(0, (f"Manual checklist: {len(pending)} of {total} "
                         "entries not done yet",
                         ["Run the commands in `manual-checklist.md`, then "
                          f"`python3 report.py {shlex.quote(outdir)}`"]))
    if ctx["strays"]:
        items.insert(0, (f"{len(ctx['strays'])} file(s) of your manual work "
                         "found outside the output folder — not in this report "
                         "(move the ones from this engagement)",
                         [f"`mv {shlex.quote(p)} "
                          f"{shlex.quote(os.path.join(os.path.abspath(outdir), w))}`"
                          for p, w in ctx["strays"]]
                         + [f"then `python3 report.py {shlex.quote(outdir)}`"]))
    if ctx["conflicts"]:
        items.insert(0, ("Manual checklist: more than one Result box ticked",
                         [f"`{k}` — tick exactly one" for k in ctx["conflicts"]]))
    L += ["## Manual follow-up (not covered by automation)", ""]
    if not items:
        L.append("_Nothing — every service had automated coverage._")
    for title, lines in items:
        L.append(f"- [ ] **{title}**")
        L.extend(f"    - {ln}" for ln in lines)
    L += ["", "**Everything automation doesn't do** — safe manual checks, "
          "then the dangerous ones it never runs: `docs/workflow/MANDATORY_CHECKS.md`.",
          "", "Hands-on steps per service: `docs/reference/MANUAL_VERIFICATION.md`; "
          "Metasploit runbook: `docs/workflow/MANUAL_METASPLOIT.md` (both in the "
          "ReconFlow folder). Per-port target lists for `set RHOSTS file:` "
          "are in `targets/`.", ""]

    if fps:
        L += ["## Appendix: false positives", "",
              "Marked false positive in `manual-checklist.md` — kept here for "
              "the record, left out of the summary.", ""]
        for f in fps:
            L += [f"- **{f['id']} · {f['info']['title']}** — "
                  + ", ".join(f"`{a['ip']}:{a['port']}`" for a in f["aff"])
                  + (f" — {f['aff'][0]['notes']}" if f["aff"][0]["notes"] else "")]
        L.append("")

    path = os.path.join(outdir, "FINDINGS.md")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
    return path


def main():
    ap = argparse.ArgumentParser(
        description="Rebuild FINDINGS.md and vulnerabilities/ from a ReconFlow "
                    "output folder. Never contacts a target.")
    ap.add_argument("outdir", help="the folder given to reconflow.py -o")
    args = ap.parse_args()
    if not os.path.isdir(args.outdir):
        ap.error(f"'{args.outdir}' is not a folder")
    try:
        build(args.outdir)
    finally:
        # Run with sudo? Keep the folder owned by the real user.
        rf.give_to_sudo_user(args.outdir)


