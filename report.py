INTERACTIVE = {"nc", "ftp", "telnet"}


def _clean(text):
    """Strip ANSI colour/cursor codes and carriage returns."""
    text = re.sub(r"\x1b\[[0-9;?]*[A-Za-z]|\x1b[()][AB012]", "", text)
    return text.replace("\r\n", "\n").replace("\r", "")


def _slug(text, n=60):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:n].strip("-")


def _fence(text):
    return "```text\n" + text.replace("```", "'''") + "\n```"


def _fill(tmpl, e):
    vals = {"ip": e["ip"], "port": e["port"], "share": "<share>", "cmd": "",
            "scheme": "http"}
    vals.update(e.get("fmt", {}))
    return tmpl.format(**vals)


def _ipkey(ip):
    return tuple(int(x) if x.isdigit() else 0 for x in re.split(r"[.:]", ip))


