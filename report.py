def build(outdir, quiet=False):
    """Rebuild FINDINGS.md + vulnerabilities/ from everything in outdir.
    Returns the FINDINGS.md path."""
    say = (lambda *a, **k: None) if quiet else rf.log
    path = os.path.join(outdir, "results.json")
    if not os.path.exists(path):
        raise SystemExit(f"{outdir}: no results.json — not a ReconFlow output "
                         "folder (or made by an older version: re-run "
                         "reconflow.py into it).")
    with open(path) as f:
        res = json.load(f)
    records, hosts = res["records"], res["hosts"]
    protos = {}
    for r in records:
        protos.setdefault((r["ip"], r["port"]), r["proto"])

    for j in res["jobs"]:  # tools colour their output; evidence must not be
        j["out"] = _clean(j.get("out") or "")
    answers, new_manual, conflicts = parse_checklist(outdir)
    ev_jobs, attached = evidence_jobs(outdir, answers, records)
    strays = find_strays(outdir, answers)
    for p, want in strays:
        say(f"{p} is outside the output folder, so it's not in the report — "
            f"if it's from this engagement, move it:  mv {shlex.quote(p)} "
            f"{shlex.quote(os.path.join(os.path.abspath(outdir), want))}", "!")
    # Folders made before msf-manual.rc existed get one on rebuild.
    if (not os.path.exists(os.path.join(outdir, "msf-manual.rc"))
            and res.get("scan_xml") is not None):
        rf.write_msf_manual_rc(res["scan_xml"], outdir, res.get("dropped") or (),
                               res.get("msf_workspace"))

    # Recon + hand-run evidence through the same rules.
    found = rf.analyze(records, res["jobs"] + ev_jobs)
    hits = []
    for p, source in msf_sources(outdir):
        hits += parse_msf_log(p, source, outdir)
    other_msf = apply_msf(found, hits, protos)

    # Checklist ticks with nothing behind them (risky checks confirmed by
    # hand, or confirmed findings automation no longer sees).
    for key, a in answers.items():
        if a["result"] != "confirmed":
            continue
        try:
            _, fid, ip, port, proto = key.split("|")
            port = int(port)
        except ValueError:
            continue
        if fid not in rf.FINDING_INFO and not fid.startswith("nse:"):
            continue
        if not any((e["ip"], e["port"], e["proto"]) == (ip, port, proto)
                   for e in found.get(fid, {}).values()):
            rf.add_finding(found, fid, ip, port, proto, "Manual",
                           "manual-checklist.md",
                           a["notes"] or "Marked confirmed in "
                                         "manual-checklist.md")

    infos = {fid: rf.finding_info(fid, list(found[fid].values()))
             for fid in found}
    ids = load_ids(outdir)
    assign_ids(ids, sorted(found, key=lambda f: (rf.SEV_ORDER[infos[f]["sev"]],
                                                 infos[f]["title"])), "F")
    assign_ids(ids, [f"new:{_slug(n['title'])}" for n in new_manual], "M")
    with open(os.path.join(outdir, "report-ids.json"), "w") as f:
        json.dump(ids, f, indent=1, sort_keys=True)

    # The checklist covers what automation found + the risky checks; what
    # you found by hand needs no checklist entry.
    auto = {fid: {k: e for k, e in v.items()
                  if set(e["sources"]) & {"Recon", "Metasploit (auto)"}}
            for fid, v in found.items()}
    auto = {k: v for k, v in auto.items() if v}
    checklist = ensure_checklist(
        outdir, checklist_entries(auto, res.get("risky", []), ids, infos))
    # Re-read: the first build has just created it.
    answers, _, _ = parse_checklist(outdir)

    # One model for every finding (automated + your NEW ones).
    findings = []
    for fid, by_key in found.items():
        info = dict(infos[fid])
        hp_src = defaultdict(set)  # one status per host:port, all sightings
        for e in by_key.values():
            hp_src[(e["ip"], e["port"], e["proto"])].update(e["sources"])
        aff = []
        for e in sorted(by_key.values(),
                        key=lambda e: (_ipkey(e["ip"]), e["port"], e["detail"])):
            st, notes, sev, stale = host_status(
                fid, e, hp_src[(e["ip"], e["port"], e["proto"])], answers,
                attached)
            aff.append(dict(e, status=st, notes=notes, stale=stale,
                            sev_override=sev))
        overrides = [a["sev_override"] for a in aff if a["sev_override"]]
        if overrides:
            info["sev"] = min(overrides, key=rf.SEV_ORDER.get)
        findings.append({"id": ids[fid], "fid": fid, "info": info, "aff": aff,
                         "status": summarize(list({(a["ip"], a["port"],
                                                    a["proto"]): a["status"]
                                                   for a in aff}.values())),
                         "sources": [s for s in SOURCES
                                     if any(s in a["sources"] for a in aff)]})
    for n in new_manual:
        aff = [{"ip": ip, "port": port, "proto": proto, "detail": "",
                "fmt": {}, "sources": ["Manual"], "status": "Confirmed",
                "notes": "", "stale": False, "sev_override": "",
                "evidence": [{"source": "Manual", "file": "manual-checklist.md",
                              "excerpt": n["evidence"] or "(no evidence given)"}]}
               for ip, port, proto in n["affected"]] or [
            {"ip": "?", "port": 0, "proto": "tcp", "detail": "", "fmt": {},
             "sources": ["Manual"], "status": "Confirmed", "notes": "",
             "stale": False, "sev_override": "", "evidence": []}]
        findings.append({
            "id": ids[f"new:{_slug(n['title'])}"], "fid": None,
            "info": {"sev": n["sev"], "title": n["title"],
                     "why": n["why"] or "Found manually.", "repro": [],
                     "expect": "", "next": "", "fix": n["fix"] or "—"},
            "aff": aff, "status": "Confirmed", "sources": ["Manual"]})
    findings.sort(key=lambda f: (rf.SEV_ORDER[f["info"]["sev"]],
                                 f["status"] == "False positive",
                                 f["info"]["title"]))
    for f in findings:
        f["file"] = (f"{'false-positives' if f['status'] == 'False positive' else f['info']['sev'].lower()}/"
                     f"{f['id'].lower()}-{_slug(f['info']['title'])}.md")

    ctx = {"outdir": outdir, "res": res, "records": records, "hosts": hosts,
           "findings": findings, "other_msf": other_msf, "hits": hits,
           "answers": answers, "conflicts": conflicts, "attached": attached,
           "strays": strays,
           "checklist": checklist, "msf_logs": msf_sources(outdir)}
    write_vulnerabilities(ctx)
    report = write_findings(ctx)
    live = [f for f in findings if f["status"] != "False positive"]
    say(f"report: {len(live)} finding(s), "
        f"{sum('Confirmed' in f['status'] for f in live)} confirmed, "
        f"{len(findings) - len(live)} false positive(s) -> {report}, "
        f"{os.path.join(outdir, 'vulnerabilities')}/", "+")
    return report


